#!/usr/bin/env python3
"""Links the Dreamcast build (Makefile.dc) as link.py links the PC's: every object, plus generated stubs for
whatever is still missing (a stub prints its name and stops the program). kos-cc links KOS and its C library.

    port/tools/link_dc.py OUT.elf OBJ_DIR DATA_DIR"""
import pathlib, re, subprocess, sys


def link(exe, objs, extra):
    # (SH ELF names C symbols with a leading underscore: --defsym takes the symbol's own name, --wrap the C one)
    cmd = ["kos-cc", "-fno-lto", "-o", str(exe), *objs, *extra, "-Wl,--defsym=_D_3BE71C=0x3BE71C",
           "-Wl,--wrap=Progress_Main", f"-Wl,-Map={exe}.map", "-lsh4zam", "-lpthread", "-lm"]  # (sh4zam: KOS's port, kos-ports/sh4zam)
    return subprocess.run(cmd, capture_output=True, text=True)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    exe, obj, data = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
    objs = [str(o) for o in sorted(obj.glob("*.o")) + sorted(data.glob("*.o"))]
    r = link(exe, objs, [])  # first pass: ask the linker what nobody provides
    need = sorted(set(re.findall(r"undefined reference to `_?(\w+)'", r.stderr)))
    lines = ['/* Generated by port/tools/link_dc.py: one stub per symbol the Dreamcast build does not provide yet. */',
             'extern int printf(const char *, ...);', 'extern void exit(int);',
             'static void missing(const char *n) { printf("bt3: not implemented yet: %s\\n", n); exit(3); }']
    lines += [f'void {s}(void) {{ missing("{s}"); }}' for s in need]
    gen = exe.parent / "gen"
    gen.mkdir(exist_ok=True)
    (gen / "stubs.c").write_text("\n".join(lines) + "\n")
    (exe.parent / "stubs.txt").write_text("\n".join(need) + "\n")
    r = subprocess.run(["kos-cc", "-fno-lto", "-c", "-w", str(gen / "stubs.c"), "-o", str(gen / "stubs.o")], capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr)
    r = link(exe, objs, [str(gen / "stubs.o")])
    errs = [l for l in r.stderr.splitlines() if "multiple definition" in l or "undefined reference" in l or "rror" in l]
    print(f"{len(need)} stubs; link {'OK -> ' + str(exe) if r.returncode == 0 else 'FAILED'}; {len(errs)} error lines")
    if errs:
        print("\n".join(errs[:40]))
    sys.exit(r.returncode)


if __name__ == "__main__":
    main()
